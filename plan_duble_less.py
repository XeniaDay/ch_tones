def seg_ids(phrase):
    res=[]; i=0; s=phrase
    while i<len(s):
        if s[i] in EXTRA:
            res.append((None,s[i])); i+=1; continue
        for L in (4,3,2,1):
            w=s[i:i+L]
            if w in word2id:
                res.append((word2id[w],w)); i+=L; break
        else:
            return None,(i,s[i])
    return res,None

