wb2=openpyxl.load_workbook(WS+'3_0/phrases/phrases.xlsx'); ws2=wb2.active
rows=[[ws2.cell(r,c).value for c in range(1,9)] for r in range(2, ws2.max_row+1)]
cnt=Counter(str(r[3]).strip() for r in rows)
dups={p for p,n in cnt.items() if n>1}
byphrase=defaultdict(list)
for i,r in enumerate(rows):
    if str(r[3]).strip() in dups: byphrase[str(r[3]).strip()].append([i,int(r[1])])
gpw=Counter(wid for l in byphrase.values() for _,wid in l)
keeper={p: sorted(set(w for _,w in l), key=lambda w:(gpw[w],w))[0] for p,l in byphrase.items()}
need=[]
for p,l in byphrase.items():
    k=keeper[p]
    for i,wid in l:
        if wid!=k: need.append((i,wid,p))
missing=[(i,wid,p) for i,wid,p in need if (wid,p) not in R]
print("need:",len(need),"missing mapping:",len(missing))
for m in missing: print("MISS",m)

replace_idx={i for i,_,_ in need}
still_present=set()
for i,r in enumerate(rows):
    if i not in replace_idx:
        still_present.add(str(r[3]).strip())
assigned_new=set()
newset={}
problems=[]
for i,wid,p in need:
    np=R.get((wid,p))
    if np is None: continue
    if np in still_present or np in assigned_new: problems.append(('collide',i,wid,p,np)); continue
    seg,fail=seg_ids(np)
    if seg is None: problems.append(('bad-seg',i,wid,p,np,str(fail))); continue
    ids=[x for x,_ in seg if x is not None]
    if any(x>500 for x in ids): problems.append(('id>500',i,wid,p,np)); continue
    if wid not in ids: problems.append(('target-missing',i,wid,p,np)); continue
    newset[i]=(np,[str(x) for x in ids]); assigned_new.add(np)
print("assigned:",len(newset),"of",len(need))
print("PROBLEMS:")
for pr in problems: print(pr)
json.dump({str(k):v for k,v in newset.items()}, open('/tmp/newset.json','w'), ensure_ascii=False)
